#!/usr/bin/env python3
"""Regenerate engine/anthropic_price_data.py from a saved copy of https://platform.claude.com/docs/en/about-claude/pricing.md.

    python tools/gen_anthropic_pricing.py docs/pricing-snapshots/anthropic-pricing-2026-10-31.md 2026-10-31 > engine/anthropic_price_data.py

Only the "Model pricing" table (Standard tier: base input, 5m / 1h cache writes, cache hits, output) is parsed. Batch, fast mode,
data-residency (1.1x) and tool-use prices are NOT imported: the app uses none of them, and a usage report that names one of those
tiers is left unpriced rather than guessed. Model ids are derived from the page names ("Claude Opus 5.5" -> claude-opus-5-5); a page
row marked "(for prompts up to 100,000 tokens)" / "(for prompts over 100,000 tokens)" becomes the short / long context price of one
model. Rows marked "limited availability" are kept (price is stated) but are not selectable.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

SOURCES = ("https://platform.claude.com/docs/en/about-claude/pricing",)
COLS = ("input", "write_30m", "write_12h", "cached_input", "output")   # page order; write_30m = 5m write, write_12h = 1h write


def money(cell: str):
    m = re.search(r"\$([0-9]+(?:\.[0-9]+)?)\s*/\s*MTok", cell)
    return float(m.group(1)) if m else None


def slug(name: str) -> str:
    base = re.sub(r"\s*\(.*$", "", name).strip()            # drop "(retired ...)", "(limited availability)", "(for prompts ...)"
    return re.sub(r"[^a-z0-9]+", "-", base.lower()).strip("-")


def parse(text: str) -> tuple[dict, dict]:
    out: dict[str, dict] = {}
    thresholds: dict[str, int] = {}
    in_table = False
    for line in text.splitlines():
        if line.startswith("## Model pricing"):
            in_table = True
            continue
        if in_table and line.startswith("## "):
            break
        if not in_table or not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 6 or cells[0] in ("Model",) or set(cells[0]) <= {":", "-", " "}:
            continue
        name = cells[0]
        if not name.startswith("Claude "):
            continue
        rates = dict(zip(COLS, map(money, cells[1:6])))
        mid = slug(name)
        tier = out.setdefault(mid, {}).setdefault("standard", {})
        up_to = re.search(r"up to ([0-9,]+) tokens", name)
        over = re.search(r"over ([0-9,]+) tokens", name)
        if up_to:
            tier["short"] = rates
            thresholds[mid] = int(up_to.group(1).replace(",", "")) + 1     # first prompt length billed at the LONG price
        elif over:
            tier["long"] = rates
        else:
            tier["short"] = rates
            tier["long"] = dict(rates)          # one price at any prompt length (1M window at standard pricing)
    return out, thresholds


def main() -> None:
    path, verified_at = Path(sys.argv[1]), sys.argv[2]
    raw = path.read_bytes()
    data, thresholds = parse(raw.decode("utf-8"))
    print('"""GENERATED by tools/gen_anthropic_pricing.py - do not edit by hand.\n')
    print(f"Source snapshot: docs/pricing-snapshots/{path.name} (sha256 {hashlib.sha256(raw).hexdigest()})")
    print("Units: USD per 1,000,000 tokens. write_30m = the 5-minute cache write price, write_12h = the 1-hour cache write price")
    print("(the field names are shared with the OpenAI table). short / long = prompt length below / at-or-above LONG_FROM[model] tokens; a")
    print('model absent from LONG_FROM has one price at any length. A request\'s prompt length counts ALL its input tokens, cache reads and writes included."""')
    print("\nPRICE_VERSION = %r" % f"anthropic-api-{verified_at}")
    print("VERIFIED_AT = %r" % verified_at)
    print("SOURCES = %r" % (SOURCES,))
    print("LONG_FROM: dict[str, int] = %r" % (thresholds,))
    print("\nPRICES: dict[str, dict[str, dict]] = {")
    for model in sorted(data):
        print(f"    {model!r}: {{")
        for t, v in data[model].items():
            print(f"        {t!r}: {v!r},")
        print("    },")
    print("}")


if __name__ == "__main__":
    main()
