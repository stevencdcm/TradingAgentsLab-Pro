#!/usr/bin/env python3
"""Regenerate engine/gemini_price_data.py from a saved copy of https://ai.google.dev/gemini-api/docs/pricing (HTML).

    python tools/gen_gemini_pricing.py docs/pricing-snapshots/gemini-pricing-2026-10-31.html 2026-10-31 > engine/gemini_price_data.py

Only the models listed in IDS (the ones this app can select) are read, and only the paid-tier STANDARD table: "Input price",
"Output price (including thinking tokens)" and "Context caching price" (the cache READ price; the per-hour cache STORAGE fee is not
imported and is therefore never part of a computed cost). Text input rows are used where the page splits by modality. A model whose
page text cannot be parsed here raises, so a layout change fails loudly instead of silently pricing wrong. A model that is not on the
page (e.g. gemini-2.0-flash today) is simply absent: its cost stays unknown.
"""
from __future__ import annotations

import hashlib
import html as htmllib
import re
import sys
from pathlib import Path

SOURCES = ("https://ai.google.dev/gemini-api/docs/pricing",)
IDS = ("gemini-2.5-pro", "gemini-2.5-flash", "gemini-3.1-flash-lite", "gemini-2.0-flash")
LABELS = {"input": "Input price", "output": "Output price (including thinking tokens)", "cached_input": "Context caching price"}


def _cell(block: str, label: str) -> list[str]:
    m = re.search(re.escape(label) + r"</td>\s*<td>.*?</td>\s*<td>(.*?)</td>", block, re.S)
    if not m:
        raise ValueError(f"label {label!r} not found")
    return [htmllib.unescape(re.sub(r"<[^>]+>", "", x)).strip() for x in re.split(r"<br\s*/?>", m.group(1))]


def _rates(lines: list[str]) -> tuple[float, float | None]:
    """(short, long) price from the lines of one cell. 'prompts <= 200k' / 'prompts > 200k' split a model; otherwise one price (the text
    row when the page splits by modality)."""
    short = long = None
    for ln in lines:
        m = re.match(r"\$([0-9.]+)(.*)", ln)
        if not m:
            continue
        rest = m.group(2)
        v = float(m.group(1))
        if "prompts > 200k" in rest:
            long = v
        elif "prompts <= 200k" in rest:
            short = v
        elif short is None and ("storage" not in rest) and ("audio" not in rest):
            short = v
    if short is None:
        raise ValueError("no price in " + repr(lines))
    return short, long


def parse(text: str) -> tuple[dict, dict]:
    out: dict[str, dict] = {}
    long_from: dict[str, int] = {}
    for mid in IDS:
        starts = [m.start() for m in re.finditer(re.escape(mid), text)]
        block = None
        for s in starts:                                   # the section whose Standard table follows the id (not a nav/link mention)
            seg = text[s:s + 1500]
            if "Standard" in seg and "Input price" in text[s:s + 4000]:
                block = text[s:s + 4000]
                break
        if block is None:
            continue
        # cut at the Batch table: only Standard is imported
        block = block.split("Batch", 1)[0] if "Batch" in block else block
        try:
            vals = {k: _rates(_cell(block, lab)) for k, lab in LABELS.items()}
        except ValueError:
            continue
        short = {k: v[0] for k, v in vals.items()} | {"write_30m": None, "write_12h": None}
        lng = {k: (v[1] if v[1] is not None else v[0]) for k, v in vals.items()} | {"write_30m": None, "write_12h": None}
        if any(v[1] is not None for v in vals.values()):
            long_from[mid] = 200001
        out[mid] = {"standard": {"short": short, "long": lng}}
    return out, long_from


def main() -> None:
    path, verified_at = Path(sys.argv[1]), sys.argv[2]
    raw = path.read_bytes()
    data, long_from = parse(raw.decode("utf-8"))
    print('"""GENERATED by tools/gen_gemini_pricing.py - do not edit by hand.\n')
    print(f"Source snapshot: docs/pricing-snapshots/{path.name} (sha256 {hashlib.sha256(raw).hexdigest()})")
    print("Units: USD per 1,000,000 tokens, paid tier, Standard processing, text input. Output includes thinking tokens. The cache STORAGE fee is not")
    print('imported. short = prompt up to 200k tokens, long = over 200k (only models that split). Prices the page dates in the future are NOT imported."""')
    print("\nPRICE_VERSION = %r" % f"gemini-api-{verified_at}")
    print("VERIFIED_AT = %r" % verified_at)
    print("SOURCES = %r" % (SOURCES,))
    print("LONG_FROM: dict[str, int] = %r" % (long_from,))
    print("\nPRICES: dict[str, dict[str, dict]] = {")
    for model in sorted(data):
        print(f"    {model!r}: {{")
        for t, v in data[model].items():
            print(f"        {t!r}: {v!r},")
        print("    },")
    print("}")


if __name__ == "__main__":
    main()
