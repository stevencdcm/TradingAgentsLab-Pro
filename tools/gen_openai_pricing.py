#!/usr/bin/env python3
"""Regenerate engine/openai_price_data.py from a saved copy of https://developers.openai.com/api/docs/pricing.md.

    python tools/gen_openai_pricing.py docs/pricing-snapshots/openai-pricing-2026-10-31.md 2026-10-31 > engine/openai_price_data.py

Only the token-priced text models of the "Flagship models" section (Standard / Batch / Flex / Fast / Ultrafast) are parsed;
cyber, life-science, multimodal, image and fine-tuning rows are not selectable here and are left out. The snapshot file is
committed next to the generated module so every number can be traced to the page text it came from.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

SOURCES = ("https://developers.openai.com/api/docs/pricing", "https://openai.com/api/pricing")
LONG_COLS = ("input", "output", "cached_input", "write_30m", "write_12h")


def money(cell: str):
    cell = cell.strip()
    m = re.fullmatch(r"\$([0-9]+(?:\.[0-9]+)?)", cell)
    return float(m.group(1)) if m else None


def parse(text: str) -> dict:
    out: dict[str, dict] = {}
    tier = None
    for line in text.splitlines():
        if line.startswith("Cyber models"):
            break
        h = re.match(r"^###? (Standard|Batch|Fast|Ultrafast) pricing data", line)
        if h:
            tier = h.group(1).lower()
            continue
        h = re.match(r"^#### (Batch|Flex)\s*$", line)
        if h:
            tier = h.group(1).lower()
            continue
        if not line.startswith("|") or tier is None:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells[0] in ("Model", "---") or set(cells[0]) <= {"-", " "}:
            continue
        name = re.sub(r"\s*\(<272K context length\)", "", cells[0])
        if len(cells) == 11:
            short = dict(zip(LONG_COLS, map(money, cells[1:6])))
            lng = dict(zip(LONG_COLS, map(money, cells[6:11])))
            if lng["input"] is None:
                lng = None
        elif len(cells) == 4:
            short = {"input": money(cells[1]), "output": money(cells[2]), "cached_input": money(cells[3]), "write_30m": None, "write_12h": None}
            lng = None
        else:
            continue
        out.setdefault(name, {})[tier] = {"short": short, "long": lng}
    return out


def main() -> None:
    path, verified_at = Path(sys.argv[1]), sys.argv[2]
    raw = path.read_bytes()
    data = parse(raw.decode("utf-8"))
    print('"""GENERATED by tools/gen_openai_pricing.py - do not edit by hand.\n')
    print(f"Source snapshot: docs/pricing-snapshots/{path.name} (sha256 {hashlib.sha256(raw).hexdigest()})")
    print('Units: USD per 1,000,000 tokens. None = the page shows "-" (no such price). short = input <= 272K tokens, long = more."""')
    print("\nPRICE_VERSION = %r" % f"openai-api-{verified_at}")
    print("VERIFIED_AT = %r" % verified_at)
    print("SOURCES = %r" % (SOURCES,))
    print("\nPRICES: dict[str, dict[str, dict]] = {")
    for model in sorted(data):
        print(f"    {model!r}: {{")
        for t, v in data[model].items():
            print(f"        {t!r}: {v!r},")
        print("    },")
    print("}")


if __name__ == "__main__":
    main()
