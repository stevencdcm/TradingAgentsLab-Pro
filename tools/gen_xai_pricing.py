#!/usr/bin/env python3
"""Regenerate engine/xai_price_data.py from a saved copy of https://docs.x.ai/docs/models (markdown).

    python tools/gen_xai_pricing.py docs/pricing-snapshots/xai-models-2026-10-31.md 2026-10-31 > engine/xai_price_data.py

Only the "Text API Pricing" table is parsed. A model listed with two rows ("< 200k prompt tokens" / ">= 200k prompt tokens") has a
short and a long price: per the page, a request whose prompt REACHES the threshold is billed at the higher rate for all tokens.
Ids are exactly as the page writes them (e.g. grok-4.20-0309-reasoning); bare aliases the page does not list are NOT priced here.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

SOURCES = ("https://docs.x.ai/docs/models",)
COLS = ("input", "cached_input", "output")


def money(cell: str):
    m = re.fullmatch(r"\$([0-9]+(?:\.[0-9]+)?)", cell.strip())
    return float(m.group(1)) if m else None


def parse(text: str) -> tuple[dict, dict]:
    out: dict[str, dict] = {}
    long_from: dict[str, int] = {}
    on = False
    for line in text.splitlines():
        if line.startswith("### Text API Pricing"):
            on = True
            continue
        if on and line.startswith("###"):
            break
        if not on or not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        m = re.match(r"^(\S+) \((<|≥|>=) (\d+)k prompt tokens\)$", cells[0])
        if not m or len(cells) != 5:
            continue
        mid, op_, k = m.group(1), m.group(2), int(m.group(3)) * 1000
        vals = dict(zip(COLS, map(money, cells[2:5])))
        rates = {"input": vals["input"], "output": vals["output"], "cached_input": vals["cached_input"], "write_30m": None, "write_12h": None}
        tier = out.setdefault(mid, {}).setdefault("standard", {})
        if op_ == "<":
            tier["short"] = rates
        else:
            tier["long"] = rates
            long_from[mid] = k
    return out, long_from


def main() -> None:
    path, verified_at = Path(sys.argv[1]), sys.argv[2]
    raw = path.read_bytes()
    data, long_from = parse(raw.decode("utf-8"))
    print('"""GENERATED by tools/gen_xai_pricing.py - do not edit by hand.\n')
    print(f"Source snapshot: docs/pricing-snapshots/{path.name} (sha256 {hashlib.sha256(raw).hexdigest()})")
    print('Units: USD per 1,000,000 tokens. short = prompt below LONG_FROM[model] tokens, long = at or above it (all tokens of the request)."""')
    print("\nPRICE_VERSION = %r" % f"xai-api-{verified_at}")
    print("VERIFIED_AT = %r" % verified_at)
    print("SOURCES = %r" % (SOURCES,))
    print("LONG_FROM: dict[str, int] = %r" % (long_from,))
    print("\nPRICES: dict[str, dict[str, dict]] = {")
    for model in sorted(data):
        print(f"    {model!r}: {{")
        for t, v in data[model].items():
            print(f"        {t!r}: {v!r},")
        print("    },")
    print("}")


if __name__ == "__main__":
    main()
